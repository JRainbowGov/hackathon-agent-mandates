"""Generate the synthetic pupil + school extract across cohorts and write the files."""

from __future__ import annotations

import hashlib
import json
from typing import TYPE_CHECKING, Any

import numpy as np
import pandas as pd
import yaml

from mcp_server.synth import census
from mcp_server.synth import pupils as pupil_gen
from mcp_server.synth.academic_year import AcademicYear
from mcp_server.synth.schemas import (
    DISPLAY_NAMES,
    PSEUDO_ID,
    SCHOOLS,
    SYNTHETIC_FIRST_NAMES,
    SYNTHETIC_LAST_NAMES,
    SYNTHETIC_SCHOOL_NAMES,
    TABLE_COLUMNS,
    TABLES,
)

if TYPE_CHECKING:
    from pathlib import Path

FILE_PREFIX = "synthetic_"
BANNER = "SYNTHETIC DATA. Generated by synth from mcp_server/synth/synth.yaml. No real person data."


def make_schools(cfg: dict[str, Any]) -> pd.DataFrame:
    n = int(cfg["schools"]["n"])
    names = [SYNTHETIC_SCHOOL_NAMES[i % len(SYNTHETIC_SCHOOL_NAMES)] for i in range(n)]
    if n > len(SYNTHETIC_SCHOOL_NAMES):
        names = [f"{name} {i // len(SYNTHETIC_SCHOOL_NAMES) + 1}" for i, name in enumerate(names)]
    return pd.DataFrame(
        {"URN": [f"SCH{i + 1:02d}" for i in range(n)], "SchoolName": names, "SchoolLA": str(cfg["local_authority"])}
    )[SCHOOLS]


def make_display_names(rng: np.random.Generator, ids: np.ndarray, gender: np.ndarray) -> pd.DataFrame:
    """Invented, gender-matched display names for presentations. A lookup beside the extract, never in a table."""
    first = np.empty(len(ids), dtype=object)
    for code, pool in SYNTHETIC_FIRST_NAMES.items():
        mask = gender == code
        first[mask] = rng.choice(pool, int(mask.sum()))
    last = rng.choice(SYNTHETIC_LAST_NAMES, len(ids))
    display = [f"{a} {b}" for a, b in zip(first, last, strict=True)]
    return pd.DataFrame({PSEUDO_ID: ids, "DisplayName": display, "Gender": gender})[DISPLAY_NAMES]


def classification(cfg: dict[str, Any]) -> dict[str, Any]:
    """The configured PII level per output table, checked so no table ships unlabelled or with an unknown level."""
    levels = {int(k): v for k, v in cfg["classification"]["levels"].items()}
    tables = {k: int(v) for k, v in cfg["classification"]["tables"].items()}
    missing = set(TABLES) - set(tables)
    unknown = {k: v for k, v in tables.items() if v not in levels}
    if missing or unknown:
        msg = f"classification.tables: missing {sorted(missing)}, unknown levels {unknown}"
        raise ValueError(msg)
    # every column gets a level, so a reader never needs a fallback rule
    overrides = cfg["classification"].get("columns", {})
    columns = {t: {c: int(overrides.get(t, {}).get(c, tables[t])) for c in TABLE_COLUMNS[t]} for t in TABLES}
    bad = {
        f"{t}.{c}": v
        for t, cols in overrides.items()
        for c, v in cols.items()
        if c not in TABLE_COLUMNS.get(t, []) or int(v) not in levels or int(v) > tables[t]
    }
    if bad:
        msg = f"classification.columns: unknown column, unknown level or above its table's level {bad}"
        raise ValueError(msg)
    return {"levels": levels, "tables": tables, "columns": columns}


def _ids(start: int, n: int) -> np.ndarray:
    return np.array([f"P{start + i + 1:04d}" for i in range(n)], dtype=object)


def generate_cohort(
    rng: np.random.Generator,
    year: AcademicYear,
    nc_year: int,
    n: int,
    *,
    cfg: dict[str, Any],
    schools: pd.DataFrame,
    start: int = 0,
) -> dict[str, pd.DataFrame]:
    """Census, deprivation and display-name tables for one cohort. Pupil IDs run on from ``start``."""
    pupils = pupil_gen.generate_pupils(rng, n, cfg)
    ids = _ids(start, n)
    urns = schools["URN"].to_numpy()[pupils["school_idx"].to_numpy()]
    return {
        "personal_data_school_census": census.census_rows(rng, pupils, ids, year, nc_year, cfg=cfg, urns=urns),
        "personal_data_deprivation": census.deprivation_rows(pupils, ids, str(cfg["local_authority"])),
        "display_names": make_display_names(rng, ids, pupils["Gender"].to_numpy()),
    }


def generate_extract(cfg: dict[str, Any], seed: int | None = None) -> tuple[dict[str, pd.DataFrame], dict[str, Any]]:
    """All tables (keyed as in :data:`synth.schemas.TABLES`) and the manifest."""
    seed = int(cfg["seed"] if seed is None else seed)
    rng = np.random.default_rng(seed)
    schools = make_schools(cfg)
    nc_year, n = int(cfg["nc_year"]), int(cfg["n_per_cohort"])
    collected: dict[str, list[pd.DataFrame]] = {}
    for k, label in enumerate(cfg["cohorts"]):
        tables = generate_cohort(rng, AcademicYear.parse(label), nc_year, n, cfg=cfg, schools=schools, start=k * n)
        for key, frame in tables.items():
            collected.setdefault(key, []).append(frame)
    out = {key: pd.concat(frames, ignore_index=True) for key, frames in collected.items()}
    out["schools"] = schools
    # No timestamp: the manifest is deterministic for a given config + seed, so it can be committed with the CSVs.
    manifest = {
        "banner": BANNER,
        "data_source": "synthetic",
        "file_prefix": FILE_PREFIX,
        "seed": seed,
        "cohorts": list(cfg["cohorts"]),
        "row_counts": {key: len(frame) for key, frame in out.items()},
        "classification": classification(cfg),
    }
    return out, manifest


def write_extract(tables: dict[str, pd.DataFrame], manifest: dict[str, Any], out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for key in TABLES:
        path = out_dir / f"{FILE_PREFIX}{key}.csv"
        tables[key].to_csv(path, index=False)
        written.append(path)
    manifest_path = out_dir / f"{FILE_PREFIX}manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    written.append(manifest_path)
    return written
